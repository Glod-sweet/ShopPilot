-- -------------------------------------------------------------
-- 向量化文本（embedding 由 scripts/embed_backfill.py 生成）
-- content 拼接规则：标题 + 副标题 + 卖点 + 品类名 + 品牌名 + 场景词
-- -------------------------------------------------------------
INSERT INTO sp_product_embedding
(product_id, content, content_hash, embedding, dim, model, category_id, brand_id, price, on_shelf, stock)
SELECT p.id,
       CONCAT_WS(' | ',
                 p.title,
                 IFNULL(p.sub_title, ''),
                 IFNULL(p.selling_points, ''),
                 c.name,
                 b.name,
                 IFNULL((SELECT GROUP_CONCAT(s.name SEPARATOR '、')
                         FROM sp_product_scene ps JOIN sp_scene s ON s.id = ps.scene_id
                         WHERE ps.product_id = p.id), '')
       ),
       -- MySQL 9.x 已移除 MD5()，改用 SHA2 前 32 位（仅作内容指纹，非安全用途）
       LEFT(SHA2(CONCAT_WS('|', p.id, p.title, IFNULL(p.selling_points, '')), 256), 32),
       NULL, 0, 'pending',
       p.category_id, p.brand_id, p.price, p.on_shelf, p.stock
FROM sp_product p
JOIN sp_category c ON c.id = p.category_id
LEFT JOIN sp_brand b ON b.id = p.brand_id;

